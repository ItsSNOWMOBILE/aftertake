export function applyTemplate(current: Recipe, template: Template): Recipe {
  if (current.clip.kind === 'image' && template.recipe.pipeline !== 'cinema')
    throw Error('Choose a video source for this recipe.');
  const cinema = template.recipe.pipeline === 'cinema';
  const result: Recipe = {
    ...current,
    pipeline: template.recipe.pipeline,
    editReference: undefined,
    endFrame: undefined,
    transfer: undefined,
    directionStrength: template.recipe.directionStrength || 1,
    ...(cinema
      ? {
          cinema: { ...template.recipe.cinema! },
          prompt:
            current.pipeline === 'cinema'
              ? current.prompt
              : 'A calm, realistic continuous shot of this place. Fine textures stay coherent, with gentle natural motion.',
        }
      : { prompt: template.recipe.prompt }),
  };
  if (template.recipe.pipeline === 'motion-transfer') {
    result.prompt =
      current.pipeline === 'motion-transfer'
        ? current.prompt
        : 'A continuous shot of the character in the appearance image performing the gesture from the driving video. Preserve the character and scene.';
    result.transfer = {
      scope: template.recipe.transfer?.scope || 'frame',
      reference: current.pipeline === 'motion-transfer' ? current.transfer?.reference : undefined,
      motionCaption:
        current.pipeline === 'motion-transfer' ? current.transfer?.motionCaption : undefined,
      poseStrength:
        current.pipeline === 'motion-transfer' ? current.transfer?.poseStrength : undefined,
    };
  }
  if (cinema && template.recipe.endFrame && current.pipeline !== 'cinema')
    result.prompt =
      'A smooth continuous transition from the selected starting frame to the chosen ending image. Keep the camera stable and the surrounding scene coherent.';
  const d = renderDimensions(result);
  result.cue = {
    ...current.cue,
    end: Math.min(current.cue.end, d.duration),
    start: Math.min(current.cue.start, Math.max(0, Math.min(current.cue.end, d.duration) - 0.1)),
    anchor: Math.min(current.cue.anchor || 0, Math.max(0, d.duration - 1 / d.fps)),
  };
  return result;
}

export function filterTemplates(
  templates: Template[],
  category: 'all' | Template['category'],
  query: string,
) {
  const words = query.toLocaleLowerCase().trim().split(/\s+/).filter(Boolean);
  return templates.filter(
    (item) =>
      (category === 'all' || item.category === category) &&
      words.every((word) =>
        [item.title, item.description, ...item.tags].join(' ').toLocaleLowerCase().includes(word),
      ),
  );
}
